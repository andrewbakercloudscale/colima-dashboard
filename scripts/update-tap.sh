#!/usr/bin/env bash
# Writes Formula/colima-dashboard.rb for a released version into a checkout of the Homebrew tap
# (default ../homebrew-tap), using the sha256 values in dist/checksums.txt from
# scripts/build-release.sh. With --push it also commits and pushes the tap (owner's call).
#   scripts/update-tap.sh 0.1.24 [--push]
set -euo pipefail

VERSION="${1:-}"
PUSH="${2:-}"
if [[ ! "${VERSION}" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "usage: $0 <version> [--push]" >&2
    exit 1
fi
cd "$(dirname "$0")/.."
TAP="${TAP_DIR:-../homebrew-tap}"
sum() {
    local f="colima-dashboard_${VERSION}_darwin_$1.tar.gz"
    awk -v f="${f}" '$2 == f { print $1 }' dist/checksums.txt | grep -E '^[0-9a-f]{64}$' ||
        { echo "no checksum for ${f} in dist/checksums.txt" >&2; exit 1; }
}
ARM="$(sum arm64)"
AMD="$(sum amd64)"
URL="https://github.com/andrewbakercloudscale/colima-dashboard/releases/download/v${VERSION}"
mkdir -p "${TAP}/Formula"
cat >"${TAP}/Formula/colima-dashboard.rb" <<RUBY
# Generated by scripts/update-tap.sh in andrewbakercloudscale/colima-dashboard. Do not edit by hand.
class ColimaDashboard < Formula
  desc "Local web dashboard for Colima: containers, images, logs, Kubernetes and fixes"
  homepage "https://github.com/andrewbakercloudscale/colima-dashboard"
  version "${VERSION}"
  license "Apache-2.0"

  if Hardware::CPU.arm?
    url "${URL}/colima-dashboard_${VERSION}_darwin_arm64.tar.gz"
    sha256 "${ARM}"
  else
    url "${URL}/colima-dashboard_${VERSION}_darwin_amd64.tar.gz"
    sha256 "${AMD}"
  end

  depends_on "colima"
  depends_on "docker"
  depends_on "docker-buildx"
  depends_on "docker-compose"
  depends_on :macos

  def install
    bin.install "colima-dashboard"
  end

  service do
    run [opt_bin/"colima-dashboard", "--no-browser"]
    keep_alive true
    log_path var/"log/colima-dashboard.log"
    error_log_path var/"log/colima-dashboard.log"
  end

  def caveats
    <<~EOS
      Start it now and at every login:
        brew services start colima-dashboard
      or run it once (opens your browser signed in):
        colima-dashboard
      Then open http://127.0.0.1:7766 and press Start to create your first VM.
      Diagnostics offers a one-click fix if docker cannot find compose or buildx.
      Updates come through: brew upgrade colima-dashboard
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/colima-dashboard version")
  end
end
RUBY
echo "wrote ${TAP}/Formula/colima-dashboard.rb for ${VERSION}"
if [[ "${PUSH}" == "--push" ]]; then
    git -C "${TAP}" add Formula/colima-dashboard.rb
    git -C "${TAP}" commit -q -m "colima-dashboard ${VERSION}"
    git -C "${TAP}" push -q origin HEAD
    echo "pushed the tap"
fi
